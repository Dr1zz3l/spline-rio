#!/usr/bin/env python3
"""Export the live ROS spline node's solver profile FROM the harness
(2026-10-13).  Runs validate_live_solver.py with the canonical deployed spline
command and RIO_DUMP_NODE_PROFILE (the harness resolves solver.yaml +
solver_cpp.yaml + bags.yaml + the canonical --set flags exactly as in an
offline run, builds the SolverConfig with _sw_solver_config and exits before
solving), then writes the node's generated profile
  mmwave_ti_ros/ros1_driver/src/rio_ros/config/rio_spline_profile.yaml
Never hand-edit that file; re-run this after any deployment.

Run from analysis/:  ../.venv/bin/python3 export_spline_node_config.py [bag]
"""
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'mmwave_ti_ros/ros1_driver/src/rio_ros/config/rio_spline_profile.yaml'
BAG = sys.argv[1] if len(sys.argv) > 1 else 'slow_racing_best_velocity'
# the canonical deployed spline command (CLAUDE.md "Current Results")
CANON = ['--mocap-yaw', '--cpp', '--sliding-window', '--no-plot',
         '--set', 'marg_prior_scale=1.0', '--set', 'accel_soft_sigma=8.0',
         '--set', 'dt_pos=0.04', '--set', 'dt_ori=0.016', '--set', 'lambda_heading=0.6',
         '--set', 'lock_extrinsics=1', '--set-ext', 'rotation_euler_deg=[180.0,27.5,1.0]']

with tempfile.TemporaryDirectory() as td:
    js = Path(td) / 'profile.json'
    env = dict(os.environ, RIO_DUMP_NODE_PROFILE=str(js))
    for k in ('RIO_BW_S0', 'RIO_BW_COEF', 'RIO_BW_S0_SCALE'):
        env.pop(k, None)
    r = subprocess.run([sys.executable, 'validate_live_solver.py', BAG] + CANON,
                       cwd=ROOT / 'analysis', env=env, capture_output=True, text=True)
    if not js.exists():
        sys.exit('harness did not dump a profile:\n' + r.stdout[-3000:] + r.stderr[-3000:])
    prof = json.loads(js.read_text())

# the front-end constants that rio_frontend.py hard-codes must agree
sys.path.insert(0, str(ROOT / 'mmwave_ti_ros/ros1_driver/src/rio_ros/scripts'))
import rio_frontend as fe  # noqa: E402
assert abs(fe.BW_COS_FLOOR - prof['bearing_cos_floor']) < 1e-12, 'cos floor drifted'
assert all(abs(a - b) < 1e-12 for a, b in zip((fe.AL_SIGMA0, fe.AL_OMEGA0, fe.AL_SIGMA_AL),
                                               prof['alias_weight'])), 'alias weight drifted'

ext = prof['extrinsics']
node = {
    '# GENERATED by analysis/export_spline_node_config.py from the harness': None,
    'rotation_euler_deg': ext['rotation_euler_deg'],
    'translation_body_m': ext['translation_body_m'],
    'radar_imu_offset_sec': ext['radar_imu_offset_sec'],
    'imu_mocap_offset_sec': ext['imu_mocap_offset_sec'],
    'imu_misalign_deg': ext['imu_misalign_deg'],
    'gyro_scale': ext['gyro_scale'],
    'accel_lag_sec': ext.get('accel_lag_sec') or 0.0,
    'doppler_v_max': prof['doppler_v_max'],
    'alias_repair': prof['alias_repair'],
    'radar_ransac_threshold': prof['radar_ransac_threshold'],
    'min_range': prof['min_range'],
    'bearing_law': prof['bearing_law'],
    'radar_frame_sc_a': prof['radar_frame_sc_a'],
    'radar_frame_sc_b': prof['radar_frame_sc_b'],
    'window_duration': prof['window_duration'],
    'stride_sec': prof['window_stride'],
    'solver_config': prof['solver_config'],
}
node.pop('# GENERATED by analysis/export_spline_node_config.py from the harness')
hdr = ("# GENERATED by analysis/export_spline_node_config.py from the harness's resolved\n"
       f"# canonical spline config (bag {BAG}); DO NOT EDIT -- re-run the exporter after\n"
       "# any deployment.  Loaded by rio_spline.launch next to rio_spline_params.yaml.\n")
OUT.write_text(hdr + yaml.safe_dump(node, sort_keys=False, default_flow_style=None))
print(f"wrote {OUT} ({len(prof['solver_config'])} solver fields)")
